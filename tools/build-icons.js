// Copies the Lucide icons the UI uses into ui/icons.js (window.ICONS: name -> inner SVG).
const fs = require('fs');
const path = require('path');
const names = ['layout-grid', 'layers', 'puzzle', 'rocket', 'list-checks', 'search', 'bell', 'plus', 'chevron-right',
  'x', 'refresh-cw', 'sun', 'moon', 'server', 'shopping-bag', 'cloud', 'message-circle', 'square-terminal', 'folder',
  'external-link', 'star', 'trash-2', 'sparkles', 'triangle-alert', 'circle-check', 'activity', 'users', 'package',
  'git-commit-horizontal', 'calendar', 'clock', 'database', 'shield-check', 'hard-drive', 'mail', 'flame', 'target',
  'sunrise', 'settings', 'bot', 'cpu', 'battery', 'battery-charging', 'battery-low', 'play', 'square', 'timer', 'clipboard-copy',
  'check', 'folder-plus', 'plug', 'coffee', 'monitor', 'hourglass', 'arrow-right', 'key-round', 'pencil', 'loader', 'circle-help', 'memory-stick'];
const dir = path.join(__dirname, '..', 'node_modules', 'lucide-static', 'icons');
const out = {};
for (const n of names) {
  const svg = fs.readFileSync(path.join(dir, `${n}.svg`), 'utf8');
  out[n] = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s+/g, ' ').trim();
}
fs.writeFileSync(path.join(__dirname, '..', 'ui', 'icons.js'),
  '// Lucide icons (ISC licence), generated by tools/build-icons.js\nwindow.ICONS = ' + JSON.stringify(out, null, 1) + ';\n');
console.log(Object.keys(out).length, 'icons');
